'use strict';
/*
 * Accès à la base de données.
 *  - PostgreSQL si la variable d'environnement DATABASE_URL est définie (recommandé en production) ;
 *  - sinon SQLite dans un fichier local (DB_PATH, par défaut softmoto.db) : pratique pour essayer en local.
 *
 * Toutes les requêtes s'écrivent avec des « ? » et s'appellent avec await :
 *   await db.get(sql, [params])      -> une ligne (ou undefined)
 *   await db.all(sql, [params])      -> toutes les lignes
 *   await db.run(sql, [params])      -> { changes }
 *   await db.insertId(sql, [params]) -> id de la ligne insérée
 *   await db.tx(async (tx) => {...}) -> transaction (tx a les mêmes méthodes + tx.lock)
 */
const path = require('path');

const URL = process.env.DATABASE_URL || '';
const dialect = /^postgres(ql)?:\/\//i.test(URL) ? 'postgres' : 'sqlite';

// Sur Render le disque est effacé à chaque déploiement : un fichier SQLite y perdrait toutes les données.
if (dialect === 'sqlite' && (process.env.RENDER || process.env.NODE_ENV === 'production') && process.env.ALLOW_SQLITE !== '1') {
  console.error("\nERREUR : DATABASE_URL est absente.\n" +
    "En ligne, les données doivent être dans PostgreSQL : un fichier SQLite serait effacé à chaque déploiement.\n" +
    "Ajoutez la variable DATABASE_URL (adresse « Internal Database URL » de votre base Render),\n" +
    "ou ALLOW_SQLITE=1 si votre hébergeur garde le disque (disque persistant).\n");
  process.exit(1);
}

// « ? » -> « $1, $2… » (en ignorant ce qui est entre guillemets)
function versPg(sql) {
  let n = 0, out = '', q = null;
  for (let i = 0; i < sql.length; i++) {
    const c = sql[i];
    if (q) { out += c; if (c === q) q = null; continue; }
    if (c === "'" || c === '"') { q = c; out += c; continue; }
    if (c === '?') { out += '$' + (++n); continue; }
    out += c;
  }
  return out;
}

/* ------------------------------------------------------------------ */
/* PostgreSQL                                                          */
/* ------------------------------------------------------------------ */
function creerPostgres() {
  const { Pool, types } = require('pg');
  types.setTypeParser(20, (v) => parseInt(v, 10));   // BIGINT, COUNT(), SUM() -> nombre
  types.setTypeParser(1700, (v) => parseFloat(v));   // NUMERIC -> nombre
  const ssl = /^(1|true|oui|yes)$/i.test(process.env.DATABASE_SSL || '') ? { rejectUnauthorized: false } : undefined;
  const pool = new Pool({ connectionString: URL, ssl, max: Number(process.env.DB_POOL_MAX) || 10 });
  pool.on('error', (e) => console.error('Base de données (connexion inactive) :', e.message));

  const api = (q) => ({
    get: async (sql, p) => (await q.query(versPg(sql), p || [])).rows[0],
    all: async (sql, p) => (await q.query(versPg(sql), p || [])).rows,
    run: async (sql, p) => ({ changes: (await q.query(versPg(sql), p || [])).rowCount }),
    insertId: async (sql, p) => (await q.query(versPg(sql) + ' RETURNING id', p || [])).rows[0].id,
    exec: async (sql) => { await q.query(sql); },
    // Verrouille une ligne jusqu'à la fin de la transaction (évite deux enregistrements simultanés pour un même conducteur).
    lock: async (table, colonne, valeur) => { await q.query(`SELECT 1 FROM ${table} WHERE ${colonne} = $1 FOR UPDATE`, [valeur]); }
  });
  const base = api(pool);

  return {
    ...base,
    tx: async (fn) => {
      const client = await pool.connect();
      try {
        await client.query('BEGIN');
        const r = await fn(api(client));
        await client.query('COMMIT');
        return r;
      } catch (e) {
        try { await client.query('ROLLBACK'); } catch (_) { /* connexion déjà perdue */ }
        throw e;
      } finally {
        client.release();
      }
    },
    colonnes: async (table) => (await pool.query(
      'SELECT column_name FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = $1', [table]
    )).rows.map((r) => r.column_name),
    tableExiste: async (table) => (await pool.query(
      'SELECT 1 FROM information_schema.tables WHERE table_schema = current_schema() AND table_name = $1', [table]
    )).rowCount > 0,
    groupConcat: (expr) => `STRING_AGG(DISTINCT ${expr}, ',')`,
    types: { pk: 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', bigint: 'BIGINT' },
    fermer: () => pool.end()
  };
}

/* ------------------------------------------------------------------ */
/* SQLite (fichier local)                                              */
/* ------------------------------------------------------------------ */
function creerSqlite() {
  let Database = null, DatabaseSync = null;
  try { Database = require('better-sqlite3'); } catch (e) { ({ DatabaseSync } = require('node:sqlite')); }
  const fichier = process.env.DB_PATH || path.join(__dirname, 'softmoto.db');
  const raw = Database ? new Database(fichier) : new DatabaseSync(fichier);
  if (Database) { raw.pragma('journal_mode = WAL'); raw.pragma('foreign_keys = ON'); }
  else raw.exec('PRAGMA journal_mode = WAL; PRAGMA foreign_keys = ON;');

  const cache = new Map();
  const stmt = (sql) => {
    let s = cache.get(sql);
    if (!s) { if (cache.size > 300) cache.clear(); s = raw.prepare(sql); cache.set(sql, s); }
    return s;
  };
  const net = (p) => (p || []).map((v) => (v === undefined ? null : v));
  const sync = {
    get: (sql, p) => stmt(sql).get(...net(p)) || undefined,
    all: (sql, p) => stmt(sql).all(...net(p)),
    run: (sql, p) => ({ changes: Number(stmt(sql).run(...net(p)).changes) }),
    insertId: (sql, p) => stmt(sql + ' RETURNING id').get(...net(p)).id,
    exec: (sql) => { raw.exec(sql); },
    lock: () => {}   // SQLite n'autorise qu'une écriture à la fois : rien à verrouiller
  };
  const asynchrone = (o) => Object.fromEntries(Object.entries(o).map(([k, f]) => [k, async (...a) => f(...a)]));

  // SQLite n'a qu'une seule connexion : on met les opérations en file pour qu'une transaction ne soit jamais mélangée à une autre requête.
  let file = Promise.resolve();
  const enFile = (fn) => { const p = file.then(fn, fn); file = p.catch(() => {}); return p; };
  const surFile = Object.fromEntries(Object.entries(sync).map(([k, f]) => [k, (...a) => enFile(() => f(...a))]));

  return {
    ...surFile,
    tx: (fn) => enFile(async () => {
      raw.exec('BEGIN');
      try { const r = await fn(asynchrone(sync)); raw.exec('COMMIT'); return r; }
      catch (e) { try { raw.exec('ROLLBACK'); } catch (_) { /* rien à annuler */ } throw e; }
    }),
    colonnes: async (table) => sync.all(`PRAGMA table_info(${table})`).map((c) => c.name),
    tableExiste: async (table) => !!sync.get("SELECT 1 FROM sqlite_master WHERE type='table' AND name = ?", [table]),
    groupConcat: (expr) => `GROUP_CONCAT(DISTINCT ${expr})`,
    types: { pk: 'INTEGER PRIMARY KEY AUTOINCREMENT', bigint: 'INTEGER' },
    fermer: async () => { raw.close(); }
  };
}

const db = dialect === 'postgres' ? creerPostgres() : creerSqlite();
db.dialect = dialect;
// Ajoute une colonne si elle n'existe pas encore (mise à jour d'une base plus ancienne).
db.ajouterColonne = async (table, colonne, definition) => {
  if ((await db.colonnes(table)).includes(colonne)) return;
  await db.exec(`ALTER TABLE ${table} ADD COLUMN ${colonne} ${definition}`);
};
module.exports = db;
